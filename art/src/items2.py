"""Item batch 1: the items a player sees most (weapons, armor, food, tonics, loot).

Same rules as items.py: items lie in the lower half of the cell (object tier: ink outline + drop
shadow). Roles follow the game's colors for each tile: the main body / wood / cloth is the
foreground role (1-3), blades, liquids, trims and gems are the detail role (4-6), so the
per-object colors (bronze vs steel dagger, tonic types, gem kinds...) still show.

Each sprite is written as a small block of rows; place() centres it and sets it on the ground.
"""
from kit import E


def place(rows, bottom=20, dx=0):
    """Centre a block of rows horizontally (plus dx) with its last row at `bottom` (0-23)."""
    w = max(len(r) for r in rows)
    left = (16 - w) // 2 + dx
    out = [E] * 24
    top = bottom - len(rows) + 1
    for i, r in enumerate(rows):
        line = "." * left + r.ljust(w, ".")
        out[top + i] = line.ljust(16, ".")[:16]
    return out


