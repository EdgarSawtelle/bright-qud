def axle(suffix=""):
    """Wooden mill gears: a gear hub with shafts toward connected sides (n/s/e/w family)."""
    d = {k: k in suffix for k in "nsew"}
    g = [list(E) for _ in range(24)]
    for y in range(9, 16):
        for x in range(4, 12):
            if (x - 7.5) ** 2 / 16 + (y - 12) ** 2 / 12 <= 1:
                g[y][x] = "2" if (x + y) % 3 else "1"
    for x, y in ((4, 9), (11, 9), (4, 15), (11, 15), (7, 8), (8, 16)):
        g[y][x] = "3"
    g[12][7] = g[12][8] = "5"
    if d["w"]:
        for x in range(0, 4):
            g[12][x] = "3"
    if d["e"]:
        for x in range(12, 16):
            g[12][x] = "3"
    if d["n"]:
        for y in range(0, 9):
            g[y][7] = "3"
    if d["s"]:
        for y in range(16, 24):
            g[y][7] = "3"
    return ["".join(r) for r in g]
