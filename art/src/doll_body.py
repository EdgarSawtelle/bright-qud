"""Paper doll body layers: base figure, body garments, feet, hands (see docs/PAPERDOLL_BRIEF.md)."""
from b3kit import C


def fin(c):
    return c.out()


# ---------------------------------------------------------------------------------- base
def base():
    c = C()
    # head, neck (anchors as b3kit.person)
    c.r(6, 3, 9, 3, "s"); c.r(5, 4, 10, 6, "s"); c.r(6, 7, 9, 7, "s")
    c.r(10, 4, 10, 6, "S"); c.r(8, 7, 9, 7, "S")
    c.p(6, 5, "O"); c.p(9, 5, "O")
    c.r(7, 8, 8, 8, "S")
    # undershirt: shoulders, torso, sleeves
    c.r(4, 9, 11, 9, "2")
    c.r(5, 10, 10, 15, "2")
    c.r(4, 10, 4, 14, "1"); c.r(11, 10, 11, 14, "3")
    c.r(5, 9, 6, 15, "1"); c.r(10, 9, 10, 15, "3")
    c.p(11, 9, "3"); c.p(4, 9, "1")
    c.p(7, 9, "S"); c.p(8, 9, "S")           # open collar
    c.p(4, 15, "s"); c.p(11, 15, "S")        # hands
    # trousers: hips, then two legs
    c.r(5, 16, 10, 17, "2"); c.r(5, 16, 6, 17, "1"); c.r(9, 16, 10, 17, "3")
    c.r(5, 15, 10, 15, "3")                  # waistband shadow
    c.r(5, 18, 6, 21, "1"); c.r(9, 18, 10, 21, "3")
    c.r(6, 18, 6, 21, "2"); c.r(9, 18, 9, 21, "2")
    c.r(5, 22, 6, 22, "S"); c.r(9, 22, 10, 22, "S")   # bare feet
    return fin(c)


# ---------------------------------------------------------------------------------- robe
