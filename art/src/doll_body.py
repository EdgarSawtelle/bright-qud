# ---------------------------------------------------------------------------------- feet
def boots():
    c = C()
    for x0, lt, dk in ((5, "1", "2"), (9, "2", "3")):
        c.r(x0, 19, x0 + 1, 19, "5" if x0 == 5 else "6")   # cuff
        c.r(x0, 20, x0 + 1, 21, lt)
        c.p(x0 + 1, 20, dk); c.p(x0 + 1, 21, dk)
        c.r(x0 - 1, 22, x0 + 1, 22, lt)
        c.p(x0 - 1, 22, dk) if x0 == 5 else c.p(x0 + 1, 22, dk)
    c.p(4, 22, "3"); c.p(11, 22, "3")
    c.p(5, 22, "1"); c.p(10, 22, "2")
    return fin(c)


def sandals():
    c = C()
    for toe, strap, sole, a in ((6, 5, 4, "4"), (9, 10, 11, "5")):
        c.r(min(toe, strap), 20, max(toe, strap), 20, a)
        c.r(min(toe, strap), 21, max(toe, strap), 21, "s")
        c.p(toe, 22, "s"); c.p(strap, 22, a)
        c.p(sole, 22, "5" if a == "4" else "6")
    return fin(c)


# ---------------------------------------------------------------------------------- hands
def gloves():
    c = C()
    for side in (0, 1):
        x = 3 if side == 0 else 11            # 2 px wide: x, x+1 (hand pixel is col 4 / col 11)
        a, b, d = ("1", "2", "3") if side == 0 else ("2", "3", "3")
        cu = "4" if side == 0 else "5"
        c.r(x, 14, x + 1, 14, cu)
        c.r(x, 15, x + 1, 15, a if side == 0 else b)
        c.p(x + side, 15, b if side == 0 else d)
        c.r(x, 16, x + 1, 16, d if side else b)
        c.p(x + 1 - side, 16, ".") if False else None
    return fin(c)


def gauntlets():
    c = C()
    for side in (0, 1):
        x0 = 2 if side == 0 else 11
        a, b, d = ("1", "2", "3") if side == 0 else ("2", "3", "3")
        cu = ("4", "5") if side == 0 else ("5", "6")
        # flared cuff
        c.r(x0, 12, x0 + 2, 12, cu[0] if side == 0 else cu[1])
        c.r(x0, 13, x0 + 2, 13, a if side == 0 else b)
        c.r(x0 + 2 if side == 0 else x0, 13, x0 + 2 if side == 0 else x0, 13, d) if False else None
        # forearm + hand plate
        c.r(x0 + 1, 14, x0 + 2, 14, a if side == 0 else b)
        c.r(x0 + 1, 15, x0 + 2, 15, b if side == 0 else d)
        c.r(x0, 15, x0, 15, a if side == 0 else b) if side == 0 else None
        c.r(x0, 15, x0 + 3 if side == 1 else x0 + 2, 15, b) if False else None
        c.r(x0 + 1, 16, x0 + 2, 16, d if side == 0 else d)
        c.p(x0 + (1 if side == 0 else 2), 14, "5" if side == 0 else "6")
    # knuckle glints
    c.p(3, 15, "w")
    return fin(c)


def claws():
    c = C()
    c.r(3, 14, 4, 14, "4"); c.r(3, 15, 4, 15, "2")
    c.r(11, 14, 12, 14, "5"); c.r(11, 15, 12, 15, "3")
