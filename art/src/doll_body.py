# ---------------------------------------------------------------------------------- chain
def chain():
    c = C()
    # strict mail rows: ring rows alternate 1/2 every other pixel, role-3 line between rows
    for y in range(9, 18):
        for x in range(4, 12):
            if (y - 9) % 2 == 1:
                t = "3"
            else:
                t = "1" if (x + (y - 9) // 2) % 2 == 0 else "2"
            c.p(x, y, t)
        c.p(11, y, "3")
    c.r(3, 9, 3, 11, "1"); c.p(3, 10, "3"); c.p(12, 9, "2"); c.p(12, 11, "2"); c.p(12, 10, "3")
    c.p(3, 9, "2"); c.p(3, 11, "2")
    c.r(3, 12, 4, 12, "5"); c.r(11, 12, 12, 12, "6")
    c.r(4, 13, 4, 14, ".")
    c.r(5, 8, 6, 8, "2"); c.r(9, 8, 10, 8, "3"); c.p(5, 8, "1")
    c.r(7, 9, 8, 9, ".")
    c.r(5, 9, 6, 9, "4"); c.r(9, 9, 10, 9, "6")
    c.r(5, 14, 10, 14, "5"); c.p(7, 14, "y"); c.p(8, 14, "y")
    c.r(4, 18, 11, 18, "6")
    for x in (4, 6, 8, 10):
        c.p(x, 18, "5")
    return fin(c)


