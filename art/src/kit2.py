"""Region batch 6: creatures and plants of the jungles, hills, canyons, flower fields, ruins, salt
dunes and waters after Joppa. Same caricature rules as kit.py (big heads, chunky bodies, seen
slightly from above, role colors 1-6 so the seed's colors still apply).

body(rows) centres a sprite of any width <= 16, sets its feet on row `bottom` and adds the
translucent ground shadow underneath.
"""
from kit import (E, HAIR_LONG, HOOD, ROBE, SPEAR, STAFF, GUN, BOW, CLUB, SWORD, TURBAN, compose, human)


def body(rows, bottom=20, shadow=True, dx=0):
    w = max(len(r) for r in rows)
    assert w <= 16, rows
    left = (16 - w) // 2 + dx
    out = [E] * 24
    top = bottom - len(rows) + 1
    assert top >= 0, rows
    for i, r in enumerate(rows):
        out[top + i] = ("." * left + r.ljust(w, ".")).ljust(16, ".")[:16]
    if shadow and bottom + 2 < 24:
        sw = min(14, max(4, w - 2))
        out[bottom + 1] = ("." * ((16 - sw) // 2) + "x" * sw).ljust(16, ".")
        out[bottom + 2] = ("." * ((16 - sw + 2) // 2) + "x" * (sw - 2)).ljust(16, ".")
    return out


