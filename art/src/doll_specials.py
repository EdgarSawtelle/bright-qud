"""Paper doll SPECIAL pieces: item-specific face/* and head/* layers (see docs/doll_specials_facehead.md).
Role digits 1-3 = item main colour, 4-6 = its detail colour. Ruler: 0123456789012345"""
from b3kit import C

LAYERS = {}


def T(name, rows, y0=0, extra=None):
    c = C()
    for i, r in enumerate(rows):
        assert len(r) <= 16, (name, i, r)
        for x, ch in enumerate(r):
            if ch != ".":
                c.p(x, y0 + i, ch)
    if extra:
        extra(c)
    LAYERS[name] = c.out()


