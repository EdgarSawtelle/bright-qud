"""Work lists for the creature tiles Bright Qud hasn't drawn yet (B3 style, docs/B3_RESTYLE_BRIEF.md).

Groups variant keys that should share one sprite (e.g. eater/1..40, chiliad-X copies), marks
humanoids (Body Anatomy "Humanoid" etc.), splits the groups into N balanced batches and writes
docs/b3_worklists/more_<i>.md (sprite name | humanoid | tile keys | colors | example | description)
plus art/src/b3more_keys.py with MORE_KEYS[i] = {tile key: sprite name}.

Usage: .venv/bin/python -I tools/b3_missing.py [N=6] [prefixes=creatures] [label=more]
  label "more" (creatures) writes art/src/b3more_keys.py (MORE_KEYS, MORE_HUMANOID); any other label
  writes art/src/<label>_keys.py with BATCH_KEYS = {i: {tile key: sprite name}} and work lists
  docs/b3_worklists/<label>_<i>.md.
"""
import collections, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path[:0] = [os.path.join(ROOT, "tools"), os.path.join(ROOT, "art", "src")]
import build_mod as BM  # noqa: E402
from qudxml import Blueprints  # noqa: E402
from tile_priority import add_random_tiles, tiles_of  # noqa: E402

HUMAN_ANATOMY = {"Humanoid", "HumanoidOctohedron", "TailedHumanoid", "BirdPerson", "HumanoidTwoHeaded",
                 "HumanoidFourArmed", "SlugHumanoid", "Mopango", "Goatfolk", "HumanoidWithTail"}
SKIP = {"creatures/natural-weapon-flap"}


def group_name(k):
    """Sprite name shared by variant keys."""
    base = k.split("/", 1)[1] if "/" in k else k
    base = re.sub(r"^chiliad-", "", base)
    base = re.sub(r"^sw/", "", base)
    base = re.sub(r"(/ruined)?/\d+$", "", base)
    base = re.sub(r"[-_/]?\d+$", "", base)
    return re.sub(r"[^a-z0-9]+", "_", base).strip("_") or "creature"


def main():
    n_batches = int(sys.argv[1]) if len(sys.argv) > 1 else 6
    prefixes = tuple(p + "/" for p in (sys.argv[2] if len(sys.argv) > 2 else "creatures").split(","))
    label = sys.argv[3] if len(sys.argv) > 3 else "more"
    bp = Blueprints()
    add_random_tiles(bp)
    idx = BM.ref_index()
    built = {f[:-4] for f in os.listdir(os.path.join(BM.MOD, "Textures")) if f.endswith(".png")}
    users = collections.defaultdict(list)
    for name, o in bp.objs.items():
        if "BaseObject" in o["tags"]:
            continue
        for k in tiles_of(bp, name):
            users[k].append(name)
    missing = sorted(k for k in users if k.startswith(prefixes) and k in idx and k not in SKIP
                     and k.replace("/", "_") not in built)
    groups = collections.OrderedDict()
    for k in missing:
        groups.setdefault(group_name(k), []).append(k)
    rows = []
    for g, ks in groups.items():
        ex = sorted(u for k in ks for u in users[k])[0]
        fg, det = BM.color_letters(bp, ex)
        anat = bp.part(ex, "Body", "Anatomy") or ""
        hum = anat in HUMAN_ANATOMY
        desc = (bp.part(ex, "Description", "Short") or "").replace("\n", " ").replace("|", "/")[:200]
        dn = (bp.part(ex, "Render", "DisplayName") or ex).replace("|", "/")
        rows.append((g, hum, ks, fg, det, ex, dn, anat, desc))
    # Balance batches by group count; keep humanoids spread so every agent uses b3kit a bit.
    batches = [[] for _ in range(n_batches)]
    for i, r in enumerate(sorted(rows, key=lambda r: (not r[1], r[0]))):
        batches[i % n_batches].append(r)
    out = os.path.join(ROOT, "docs", "b3_worklists")
    os.makedirs(out, exist_ok=True)
    keys = {}
    for i, b in enumerate(batches, 1):
        lines = [f"# B3 work list: {label}_{i} ({len(b)} sprites, {sum(len(r[2]) for r in b)} tile keys)", "",
                 "sprite name | humanoid layout | tile keys | colors &F/D | example object (display name) | anatomy | game description",
                 "---|---|---|---|---|---|---"]
        keys[i] = {}
        for g, hum, ks, fg, det, ex, dn, anat, desc in b:
            lines.append(f"{g} | {'YES' if hum else ''} | {', '.join(ks)} | &{fg}/{det} | {ex} ({dn}) | {anat} | {desc}")
            for k in ks:
                keys[i][k] = g
        with open(os.path.join(out, f"{label}_{i}.md"), "w") as f:
            f.write("\n".join(lines) + "\n")
    hum = sorted(r[0] for r in rows if r[1])
    if label == "more":
        with open(os.path.join(ROOT, "art", "src", "b3more_keys.py"), "w") as f:
            f.write('"""Generated by tools/b3_missing.py: tile keys per batch for the remaining creatures."""\n\n')
            f.write(f"MORE_KEYS = {keys!r}\n\nMORE_HUMANOID = {set(hum)!r}\n")
    else:
        with open(os.path.join(ROOT, "art", "src", f"{label}_keys.py"), "w") as f:
            f.write(f'"""Generated by tools/b3_missing.py: tile keys per batch ({label})."""\n\n')
            f.write(f"BATCH_KEYS = {keys!r}\n")
    print(f"{len(missing)} keys in {len(rows)} sprites ({len(hum)} humanoid) -> {n_batches} batches:",
          [len(b) for b in batches])


if __name__ == "__main__":
    main()
