"""Work lists for the B3 character restyle (docs/B3_RESTYLE_BRIEF.md).

Writes art/src/b3keys.py: for each source group, {sprite name: [game tile keys]} plus
B3_HUMANOID (names drawn on the humanoid layout), and docs/b3_worklists/<group>.md with each
sprite's tile keys, game colors and the game's own short description, for the art agents.

Usage: .venv/bin/python -I tools/b3_worklist.py
"""
import collections, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path[:0] = [os.path.join(ROOT, "tools"), os.path.join(ROOT, "art", "src")]
import build_mod as BM  # noqa: E402
import kit as K  # noqa: E402
import kit2 as K2  # noqa: E402
import kit3a as K3A  # noqa: E402
import kit3b as K3B  # noqa: E402
import tiles as T  # noqa: E402
from qudxml import Blueprints  # noqa: E402
from tile_priority import add_random_tiles  # noqa: E402

# group -> {sprite name: grid}. Only characters and monsters (not plants drawn as scenery).
GROUPS = {
    "kit": K.CREATURES,
    "kit2": K2.CREATURES2,
    "kit3a": K3A.CREATURES3A,
    "kit3b": K3B.CREATURES3B,
    "castes": K.CASTES,
    "tiles": {n: T.SPRITES[n] for n in ("gunwing", "adventurer", "farmer", "snapjaw", "glowfish")},
}


def main():
    idx = BM.ref_index()
    bp = Blueprints()
    add_random_tiles(bp)
    users = BM.users_by_key(bp)
    targets = BM.targets(idx)
    by_id = collections.defaultdict(list)
    for k, grid, kind, flip, ex in targets:
        by_id[id(grid)].append(k)
    keys = {}
    for g, sprites in GROUPS.items():
        keys[g] = {n: sorted(set(by_id.get(id(grid), []))) for n, grid in sprites.items()}
    keys["castes"] = {k: [k] for k in K.CASTES}
    humanoid = sorted({n for g in keys for n, ks in keys[g].items() if any(k in BM.HUMANOID for k in ks)}
                      | {f"castes:{k}" for k in K.CASTES})
    with open(os.path.join(ROOT, "art", "src", "b3keys.py"), "w") as f:
        f.write('"""Generated by tools/b3_worklist.py: B3 restyle work lists. Do not edit."""\n\n')
        f.write(f"KEYS = {keys!r}\n\n")
        f.write(f"HUMANOID_KEYS = {sorted(BM.HUMANOID)!r}\n")
    out = os.path.join(ROOT, "docs", "b3_worklists")
    os.makedirs(out, exist_ok=True)
    for g, names in keys.items():
        lines = [f"# B3 work list: {g} ({len(names)} sprites)", "",
                 "name | humanoid layout | tile keys | colors &F/D | example object | game description", "---|---|---|---|---|---"]
        for n, ks in names.items():
            ex = next((sorted(users.get(k, []))[0] for k in ks if users.get(k)), None)
            fg, det = BM.color_letters(bp, ex) if ex else ("y", "w")
            desc = (bp.part(ex, "Description", "Short") or "").replace("\n", " ").replace("|", "/")[:220] if ex else ""
            hum = "YES" if any(k in BM.HUMANOID for k in ks) or g == "castes" else ""
            lines.append(f"{n} | {hum} | {', '.join(ks) or '-'} | &{fg}/{det} | {ex or '-'} | {desc}")
        with open(os.path.join(out, f"{g}.md"), "w") as f:
            f.write("\n".join(lines) + "\n")
        print(g, len(names))


if __name__ == "__main__":
    main()
